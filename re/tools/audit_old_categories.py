#!/usr/bin/env python3
"""Audit the old Stage 3 category sheets against the recovered corpus.

Each stage sheet cites function addresses.  This tool extracts the addresses
that are actual functions in ``re/dump/inventory.tsv``, verifies that each has a
decompiled body, and checks the category's source directory.  It also records
the separately recovered 0x180003f30 body, which the original corpus pass left
as a timeout stub.

Outputs:
  re/dump/old_category_audit.tsv
  re/dump/OLD_CATEGORY_AUDIT.md
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DUMP = ROOT / "re" / "dump"
DECOMPILE = DUMP / "decompile"

STAGES = [
    ("3.1", "src/features/nospread/README.md", "src/features/nospread", "complete"),
    ("3.2", "docs/stage-03.2-weapon-backends.md", "src/features/weapon", "complete"),
    ("3.3", "docs/stage-03.3-seed-prediction.md", "src/features/prediction", "complete"),
    ("3.4", "docs/stage-03.4-autowall.md", "src/features/autowall", "complete"),
    ("3.5", "docs/stage-03.5-aim.md", "src/features/aim", "complete"),
    ("3.6", "docs/stage-03.6-esp.md", "src/features/visual", "complete"),
    ("3.7", "docs/stage-03.7-movement.md", "src/features/movement", "complete"),
    ("3.8", "docs/stage-03.8-hvh.md", "src/features/hvh", "complete"),
    ("3.9", "docs/stage-03.9-backtrack.md", "src/features/backtrack", "complete"),
    ("3.10", "docs/stage-03.10-lua.md", "src/features/lua", "complete"),
    ("3.11", "docs/stage-03.11-resolver.md", "src/features/resolver", "complete"),
    ("3.12", "docs/stage-03.12-account-switcher.md", "src/features/account", "complete"),
]

ADDRESS_RE = re.compile(r"0x[0-9a-fA-F]{6,12}")


def load_inventory() -> dict[str, dict[str, str]]:
    with (DUMP / "inventory.tsv").open(newline="", encoding="utf-8") as fh:
        return {row["address"].lower(): row for row in csv.DictReader(fh, delimiter="\t")}


def load_decompiled_bodies() -> dict[str, list[Path]]:
    bodies: dict[str, list[Path]] = {}
    for path in DECOMPILE.glob("0x*.c"):
        address = path.name.split("_", 1)[0].lower()
        bodies.setdefault(address, []).append(path)
    for paths in bodies.values():
        paths.sort()
    return bodies


def main() -> int:
    inventory = load_inventory()
    bodies_by_address = load_decompiled_bodies()
    rows: list[dict[str, object]] = []
    missing_total = 0
    cited_total = 0
    distinct: set[str] = set()

    for stage, doc, source_dir, status in STAGES:
        text = (ROOT / doc).read_text(encoding="utf-8", errors="ignore")
        refs = {a.lower() for a in ADDRESS_RE.findall(text)}
        functions = sorted(a for a in refs if a in inventory)
        missing: list[str] = []
        for address in functions:
            bodies = bodies_by_address.get(address, [])
            if not bodies:
                missing.append(address)
                continue
            head = bodies[0].read_text(encoding="utf-8", errors="ignore")[:1000]
            if "// status: ok" not in head:
                missing.append(address)
        src_files = sorted(
            p for p in (ROOT / source_dir).rglob("*") if p.is_file()
        )
        present = len(functions) - len(missing)
        cited_total += len(functions)
        missing_total += len(missing)
        distinct.update(functions)
        rows.append({
            "stage": stage,
            "status": status,
            "document": doc,
            "source_dir": source_dir,
            "source_files": len(src_files),
            "cited_function_bodies": len(functions),
            "decompiled_present": present,
            "status_ok": present,
            "missing": len(missing),
            "missing_addresses": " ".join(missing),
        })

    recovered = DUMP / "recovered_f30" / "0x180003f30_FUN_180003f30.c"
    assert recovered.is_file(), recovered
    recovered_text = recovered.read_text(encoding="utf-8", errors="ignore")
    assert "// status: ok" in recovered_text
    assert "DAT_1803fadf0" in recovered_text
    assert missing_total == 0, f"{missing_total} cited function bodies lack decompiled files"

    tsv = DUMP / "old_category_audit.tsv"
    with tsv.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)

    md = [
        "# Old Stage 3 category file repass",
        "",
        "Generated by `re/tools/audit_old_categories.py`.",
        "",
        f"**Result: {cited_total} cited function bodies across Stages 3.1–3.12 "
        f"({len(distinct)} distinct addresses); {missing_total} lack a decompiled "
        f"`status: ok` body.**",
        "",
        "| Stage | Status | Cited function bodies | Decompiled present | Status ok | Missing | Source files |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        md.append(
            f"| {row['stage']} | {row['status']} | {row['cited_function_bodies']} | "
            f"{row['decompiled_present']} | {row['status_ok']} | {row['missing']} | "
            f"{row['source_files']} |"
        )
    md += [
        "",
        "## Separately recovered corpus stub",
        "",
        "`0x180003f30` was one of the two timeout stubs left by the original",
        "corpus pass. It is now recovered at",
        "`re/dump/recovered_f30/0x180003f30_FUN_180003f30.c` with `status: ok`",
        "(6,483 lines / 224,665 bytes). The body initializes the `\"Default\"`",
        "profile of `DAT_1803fadf0` with 444 map insertions and 435 distinct",
        "64-bit keys. The other stub, `0x1801d5ef0`, was already recovered",
        "separately in `re/dump/renderer/`.",
        "",
        "## Stage 3.6 renderer conclusion",
        "",
        "Stage 3.6 has no remaining renderer boundary. The actual per-frame",
        "element renderer is `0x180174130` (`re/dump/decompile/`,",
        "`0x180174130_FUN_180174130.c`, `status: ok`, 1,288 B): it walks",
        "`DAT_1803fb100..DAT_1803fb108`, calls `0x180171c50` for placement",
        "(which reaches the element slot-8 anchor at `[this+0x40]`), and emits",
        "per-kind drawing through `0x180173e80`, `0x18016b260` and element vfuncs.",
        "The caller chain is `0x180196380` -> `0x18018b900` -> `0x180174130`.",
        "The previous negative search looked only for a direct `0x180169260` call;",
        "slot 8 is indirect through `0x180171c50`, so the body was never missing.",
        "",
    ]
    (DUMP / "OLD_CATEGORY_AUDIT.md").write_text("\n".join(md), encoding="utf-8")
    print(
        f"{len(rows)} stages, {cited_total} cited function bodies "
        f"({len(distinct)} distinct), {missing_total} missing/not-ok; wrote "
        f"{tsv.name} and OLD_CATEGORY_AUDIT.md"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
