// Extracts the hash-keyed menu-config schema from the two config bodies.
//
//   0x1801aaa70  save:   FUN_1801a9{cd0,de0,ee0,ff0}(stream, key, value)
//   0x1801b2830  load:   FUN_1801aa{240,2a0,350}(map, key, &field)
//
// The save body has 221 bool, 115 int, 135 float and 8 string calls, plus one
// float written through 0x1801a9c30, for 480 inline keys.  The twelve vec4s
// written by 0x1801aa470 contribute 48 derived float keys, giving 528.
//
// Run from the repository root:
//   node re/tools/extract_config_keys.js

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..", "..");
const saveFile = path.join(
  root,
  "re",
  "dump",
  "decompile",
  "0x1801aaa70_FUN_1801aaa70.c"
);
const vec4File = path.join(
  root,
  "re",
  "dump",
  "decompile",
  "0x1801aa470_FUN_1801aa470.c"
);
const outFile = path.join(root, "src", "features", "config", "config_keys.h");

const save = fs.readFileSync(saveFile, "utf8");
const vec4 = fs.readFileSync(vec4File, "utf8");

const typeByWriter = {
  cd0: "Bool",
  de0: "Int",
  ee0: "Float",
  ff0: "String",
};

const entries = new Map();
for (const match of save.matchAll(
  /FUN_1801a9(cd0|de0|ee0|ff0)\(local_198,\s*(0x[0-9a-f]+)/g
)) {
  const key = BigInt(match[2]);
  const type = typeByWriter[match[1]];
  if (entries.has(key) && entries.get(key) !== type) {
    throw new Error(`key ${match[2]} has conflicting writers`);
  }
  entries.set(key, type);
}

// One float is written with an explicit hash string and stream insertion.
for (const match of save.matchAll(/FUN_1801a9c30\(local_1f8,\s*(0x[0-9a-f]+)\)/g)) {
  const key = BigInt(match[1]);
  if (entries.has(key) && entries.get(key) !== "Float") {
    throw new Error(`special key ${match[1]} is not a float`);
  }
  entries.set(key, "Float");
}

const vec4Bases = [];
for (const match of vec4.matchAll(/FUN_1801aa0f0\(param_1,\s*(0x[0-9a-f]+)/g)) {
  vec4Bases.push(BigInt(match[1]));
}
if (vec4Bases.length !== 12) {
  throw new Error(`expected 12 vec4 bases, found ${vec4Bases.length}`);
}

const FNV_PRIME = 0x100000001b3n;
for (const base of vec4Bases) {
  for (const component of ["r", "g", "b", "a"]) {
    const key = ((base ^ BigInt(component.charCodeAt(0))) * FNV_PRIME) &
      0xffffffffffffffffn;
    if (entries.has(key) && entries.get(key) !== "Float") {
      throw new Error(`vec4 key ${key.toString(16)} conflicts`);
    }
    entries.set(key, "Float");
  }
}

const sorted = [...entries.entries()].sort((a, b) =>
  a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0
);

const counts = { Bool: 0, Int: 0, Float: 0, String: 0 };
for (const [, type] of sorted) ++counts[type];

const lines = [];
lines.push("// Generated by re/tools/extract_config_keys.js. Do not edit by hand.");
lines.push("//");
lines.push("// Every hash key written by 0x1801aaa70 and read by 0x1801b2830.");
lines.push("// Values are the exact 64-bit FNV-1a keys from the decompiled bodies,");
lines.push("// not names: the original source used compile-time hash constants.");
lines.push("#pragma once");
lines.push("");
lines.push("#include <cstddef>");
lines.push("#include <cstdint>");
lines.push("");
lines.push("namespace sf {");
lines.push("namespace config {");
lines.push("");
lines.push("enum class ValueType : std::uint8_t { Bool, Int, Float, String };");
lines.push("");
lines.push("struct ConfigKey");
lines.push("{");
lines.push("    std::uint64_t key;");
lines.push("    ValueType type;");
lines.push("};");
lines.push("");
lines.push("inline constexpr std::uint64_t kFnvPrime = 0x100000001b3ull;");
lines.push("");
lines.push("// FNV-1a is the primitive behind the vec4 tail: 0x1801aa0f0 appends");
lines.push("// one character to the name hash with (hash ^ c) * prime.");
lines.push("inline constexpr std::uint64_t Fnv1aStep(std::uint64_t hash, char c)");
lines.push("{");
lines.push("    return (hash ^ static_cast<std::uint8_t>(c)) * kFnvPrime;");
lines.push("}");
lines.push("");
lines.push("inline constexpr std::uint64_t Vec4Key(std::uint64_t base, char component)");
lines.push("{");
lines.push("    return Fnv1aStep(base, component);");
lines.push("}");
lines.push("");
lines.push(`inline constexpr ConfigKey kConfigKeys[] = {`);
for (const [key, type] of sorted) {
  lines.push(
    `    {0x${key.toString(16).padStart(16, "0")}ull, ValueType::${type}},`
  );
}
lines.push("};");
lines.push("");
lines.push(
  "inline constexpr std::size_t kConfigKeyCount = sizeof(kConfigKeys) / sizeof(kConfigKeys[0]);"
);
lines.push("");
lines.push(`inline constexpr std::size_t kBoolKeyCount = ${counts.Bool};`);
lines.push(`inline constexpr std::size_t kIntKeyCount = ${counts.Int};`);
lines.push(`inline constexpr std::size_t kFloatKeyCount = ${counts.Float};`);
lines.push(`inline constexpr std::size_t kStringKeyCount = ${counts.String};`);
lines.push("");
lines.push("} // namespace config");
lines.push("} // namespace sf");
lines.push("");

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join("\n"));
console.log(
  `wrote ${sorted.length} keys (${counts.Bool} bool, ${counts.Int} int, ` +
    `${counts.Float} float, ${counts.String} string) to ${outFile}`
);
